/**
 * Builds the server's course data (Step 3) from the committed catalog and
 * matches: scripts/build_course_matches_server.ts writes it, the tests check
 * the committed file is exactly what this builds.
 */

import fs from 'node:fs';
import path from 'node:path';
import { KELLEY_JOB_SOCS } from '../../src/utils/kelleySocs';
import { RETIRED, type CatalogEntry } from './courseCatalog';
import { MATCH_PATHS, usable, type Match } from './courseMatch';

export const SERVER_DATA_PATH = 'api/_lib/courseMatchesData.ts';

export interface ServerCourse {
    title: string;
    provider: string;
    url: string;
    type: string;
    level?: string;
    duration?: string;
}

export interface ServerCourseData {
    catalogGenerated: string;
    matchesPromptVersion: string;
    courses: Record<string, ServerCourse>;
    jobs: Record<string, Match[]>;
    kelley: Record<string, string>;
}

export function buildServerCourseData(root: string): ServerCourseData {
    const catalog = JSON.parse(fs.readFileSync(path.join(root, MATCH_PATHS.catalog), 'utf8')) as { generated: string; entries: CatalogEntry[] };
    const matchesFile = JSON.parse(fs.readFileSync(path.join(root, MATCH_PATHS.matches), 'utf8')) as { _meta: { promptVersion: string }; matches: Record<string, Match[]> };
    return assembleServerCourseData(catalog, matchesFile, KELLEY_JOB_SOCS);
}

/** Only matched entries; throws on a match to an entry the catalog no longer has, or one that is retired. */
export function assembleServerCourseData(
    catalog: { generated: string; entries: CatalogEntry[] },
    matchesFile: { _meta: { promptVersion: string }; matches: Record<string, Match[]> },
    kelleyJobs: readonly { id: string; soc: string }[],
): ServerCourseData {
    const byId = new Map(catalog.entries.map((e) => [e.id, e]));
    const courses: Record<string, ServerCourse> = {};
    const jobs: Record<string, Match[]> = {};
    for (const soc of Object.keys(matchesFile.matches).sort()) {
        const list = matchesFile.matches[soc];
        if (list.length === 0) continue;
        for (const m of list) {
            const e = byId.get(m.id);
            if (!e) throw new Error(`${soc}: matched course ${m.id} is not in catalog.json (removed or retired)`);
            if (!usable(e) || RETIRED.test(`${e.title} ${e.description ?? ''}`)) throw new Error(`${soc}: matched course ${m.id} may not be offered (retired or generic)`);
            courses[e.id] = {
                title: e.title,
                provider: e.provider,
                url: e.url,
                type: e.type,
                ...(e.level ? { level: e.level } : {}),
                ...(e.duration ? { duration: e.duration } : {}),
            };
        }
        jobs[soc] = list.map((m) => ({ id: m.id, reason: m.reason }));
    }
    const kelley: Record<string, string> = {};
    for (const k of [...kelleyJobs].sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }))) {
        if (jobs[k.soc]) kelley[k.id] = k.soc;
    }
    const sortedCourses = Object.fromEntries(Object.entries(courses).sort(([a], [b]) => a.localeCompare(b)));
    return { catalogGenerated: catalog.generated, matchesPromptVersion: matchesFile._meta.promptVersion, courses: sortedCourses, jobs, kelley };
}

export function renderServerCourseData(d: ServerCourseData): string {
    return `/**
 * GENERATED by scripts/build_course_matches_server.ts from
 * data/course_catalog/catalog.json (${d.catalogGenerated}) and
 * data/course_catalog/matches.json (${d.matchesPromptVersion}). Do not edit.
 *
 * Server only (api/_lib/courseMatches.ts): never imported by src/, so it is
 * not in the browser bundle. Only the ${Object.keys(d.courses).length} catalog courses matched to at
 * least one of ${Object.keys(d.jobs).length} jobs; every other job gets the #99 course links.
 */

export interface ServerCourse { title: string; provider: string; url: string; type: string; level?: string; duration?: string }

export const COURSE_MATCHES_DATA: {
    catalogGenerated: string;
    matchesPromptVersion: string;
    courses: Record<string, ServerCourse>;
    jobs: Record<string, { id: string; reason: string }[]>;
    kelley: Record<string, string>;
} = ${JSON.stringify(d, null, 1)};
`;
}
