#!/usr/bin/env node
/**
 * Builds the app icons from ONE source SVG, public/icons/icon.svg.
 *
 *   node scripts/build_icons.mjs           write public/icons/icon-maskable.svg and every PNG
 *   node scripts/build_icons.mjs --check   fail if any committed file differs from a fresh build
 *
 * The maskable variant is the same art scaled into the 80% safe zone (a circle
 * of radius 40% round the centre), on the same full-bleed ground, so Android
 * can cut any shape out of it. Rendering is @resvg/resvg-js (devDependency):
 * no browser and no system tool, so every machine gets the same bytes.
 *
 * Sizes (ICONS below) are what index.html and public/manifest.webmanifest
 * link; src/__tests__/phoneApp.test.ts reads each PNG header to check them.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'public', 'icons');
const SOURCE = join(DIR, 'icon.svg');
const MASKABLE = join(DIR, 'icon-maskable.svg');

/** Art scale inside the maskable icon. The farthest art point (the ground line's
 *  ends) sits about 262 px from the centre at full size, so 0.76 puts it at 199 px,
 *  inside the 204.8 px safe circle of a 512 px icon. */
export const MASKABLE_SCALE = 0.76;

/** Every PNG: file name, source, pixel size. */
export const ICONS = [
    { file: 'apple-touch-icon.png', source: 'icon.svg', size: 180 },
    { file: 'icon-192.png', source: 'icon.svg', size: 192 },
    { file: 'icon-512.png', source: 'icon.svg', size: 512 },
    { file: 'icon-maskable-512.png', source: 'icon-maskable.svg', size: 512 },
    { file: 'favicon-32.png', source: 'icon.svg', size: 32 },
    { file: 'favicon-16.png', source: 'icon.svg', size: 16 },
];

function maskableSvg(source) {
    const open = '<g id="peaks">';
    if (source.split(open).length !== 2) throw new Error(`icon.svg must hold exactly one ${open}`);
    const s = MASKABLE_SCALE;
    // Scale about the art's middle (256, 255) and put that on the icon's centre.
    const transform = `translate(256 256) scale(${s}) translate(-256 -255)`;
    return source
        .replace(open, `<g id="peaks" transform="${transform}">`)
        .replace(/<!--[\s\S]*?-->/, '<!-- GENERATED by scripts/build_icons.mjs from icon.svg: do not edit.\n'
            + `       Maskable: the same art at ${s} scale, inside the 80% safe zone. -->`);
}

function render(svg, size) {
    const png = new Resvg(svg, {
        fitTo: { mode: 'width', value: size },
        font: { loadSystemFonts: false },
    }).render().asPng();
    return Buffer.from(png);
}

function main() {
    const check = process.argv.includes('--check');
    const source = readFileSync(SOURCE, 'utf8');
    const svgs = { 'icon.svg': source, 'icon-maskable.svg': maskableSvg(source) };
    const outputs = [[MASKABLE, Buffer.from(svgs['icon-maskable.svg'])]];
    for (const icon of ICONS) outputs.push([join(DIR, icon.file), render(svgs[icon.source], icon.size)]);

    const stale = [];
    for (const [path, bytes] of outputs) {
        const name = path.slice(ROOT.length + 1);
        if (check) {
            if (!existsSync(path) || !readFileSync(path).equals(bytes)) stale.push(name);
        } else {
            writeFileSync(path, bytes);
            console.log(`wrote ${name} (${bytes.length.toLocaleString('en-US')} bytes)`);
        }
    }
    if (check) {
        if (stale.length) {
            console.error(`Stale icons (run node scripts/build_icons.mjs): ${stale.join(', ')}`);
            process.exit(1);
        }
        console.log(`All ${outputs.length} icon files are up to date.`);
    }
}

main();
